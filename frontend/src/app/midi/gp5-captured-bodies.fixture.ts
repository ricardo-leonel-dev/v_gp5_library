export function capturedBodyBytes(index: number): Uint8Array {
  const entry = GP5_CAPTURED_BODIES[index];
  if (!entry) throw new Error(`capturedBodyBytes: no entry at index ${index}`);
  const out = new Uint8Array(entry.bodyHex.length / 2);
  for (let i = 0; i < out.length; i++) {
    out[i] = parseInt(entry.bodyHex.slice(i * 2, i * 2 + 2), 16);
  }
  return out;
}
