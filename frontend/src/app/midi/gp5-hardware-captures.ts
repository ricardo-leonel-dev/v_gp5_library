// Ground-truth record of real GP-5 reads (feature 19, T1). Each row pairs the 4 raw REC_MODELS bytes of
// one block with the category and FX title the pedal showed for it at capture time. The lookup table
// `GP5_HARDWARE_MODULE_CODES` in `gp5-module-vocabulary.ts` is written by hand and cross-checked against
// this file in the specs; the vocabulary module itself never imports it.
//
// Sources (all on preset 0 "TL DLX AMP", read with progress/gp5_webmidi_body_read_probe.html):
//   - 2026-09-28: feature 18's capture (PRE/COMP, AMP/Dark Twin, CAB/User IR 1-20), R4.
//   - 2026-09-29: the step 1c baseline and the step 1b unsaved-edit read.
//   - 2026-09-30: rounds 1-51 (every block stepped through its category list), the User IR 13 and 20
//     re-reads, and the step 1e reorder pair ("1e before" / "1e after": RVB moved before MOD).
// Deliberately left out:
//   - the "round 33" CAB row: its bytes equal round 32's (a stale read); User IR 13 was re-read later;
//   - the two 2026-09-29 "round 1" attempts: the 2026-09-30 round 1 repeats them, and the first attempt's
//     N->S code [63,0,0,15] was never named on the pedal, so it stays out of the table (resolves raw).
// Title conventions:
//   - User IR slots: `pedalFxTitle` is the canonical `User IR 1-20`; `pedalDisplayName` holds the name the
//     pedal showed (an imported IR's name, or the default `User IR <n>` of an empty slot).
//   - User-imported SnapTones: `pedalFxTitle` is `User SnapTone`; `pedalDisplayName` is the file name (R22).
//   - An empty user N->S slot shows `Empty` on the pedal, so it maps to N->S / `Empty`.

export interface Gp5HardwareCapture {
  readonly source: string;
  readonly blockIndex: number;
  readonly chainPosition: number;
  readonly rawBytes: readonly [number, number, number, number];
  readonly moduleType: string;
  readonly pedalCategory: string;
  readonly pedalFxTitle: string;
  readonly pedalDisplayName?: string;
}

type Block = readonly [
  blockIndex: number,
  chainPosition: number,
  rawBytes: readonly [number, number, number, number],
  moduleType: string,
  pedalCategory: string,
  pedalFxTitle: string,
  pedalDisplayName?: string,
];

function read(source: string, blocks: readonly Block[]): Gp5HardwareCapture[] {
  return blocks.map(
    ([blockIndex, chainPosition, rawBytes, moduleType, pedalCategory, pedalFxTitle, pedalDisplayName]) => ({
      source,
      blockIndex,
      chainPosition,
      rawBytes,
      moduleType,
      pedalCategory,
      pedalFxTitle,
      ...(pedalDisplayName === undefined ? {} : { pedalDisplayName }),
    }),
  );
}

